#!/usr/bin/env python3
"""Independently inspect the real production-writer fixture files, read-only."""
import hashlib
import importlib.util
import json
from pathlib import Path

BASE = Path('/workspace/scratch/f4dc23366b1f')
SPEC = importlib.util.spec_from_file_location('raw_audit', BASE/'hasselblad_device_validation_20261019/raw_audit/audit_dng.py')
AUDIT = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(AUDIT)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def payload(path):
    data = path.read_bytes()
    reader = AUDIT.TIFF(data)
    assert len(reader.ifds) == 1
    tags = reader.ifds[0]['tags']
    strip = b''.join(reader.read(o, n) for o, n in zip(AUDIT.numeric(tags[273]), AUDIT.numeric(tags[279])))
    field_payloads = {tag: (value['type_id'], value['count'], reader.read(value['data_offset'], value['byte_length']))
                      for tag, value in tags.items() if tag not in (273, 50717)}
    return data, tags, strip, field_payloads


def main():
    source_report = BASE/'HasselbladPhoton/development/hasselblad/DNG_EXPORT_CHECK_RESULT.json'
    report = json.loads(source_report.read_text())
    assert report['result'] == 'pass'
    for filename, checksum in report['source_hashes'].items():
        assert sha(Path(filename).read_bytes()) == checksum, filename
    original_source_record = BASE/'hasselblad-build-artifacts/native1_source_changes.json'
    original_sources = json.loads(original_source_record.read_text())
    writer_path = 'app/src/main/cpp/deps/tiny_dng_writer.h'
    original_writer = next(row for row in original_sources['changes'] if row['path'] == writer_path)
    assert sha((BASE/'HasselbladPhoton'/writer_path).read_bytes()) == original_writer['native1_sha256']
    work = Path('/tmp/hasselblad-native1a-dng-fixtures')
    cases = []
    for record in report['fixture_cases']:
        name = record['name']
        previous_path = work/'native1'/(name+'.dng')
        updated_path = work/'native1a'/(name+'.dng')
        old_file, old_tags, old_strip, old_fields = payload(previous_path)
        new_file, new_tags, new_strip, new_fields = payload(updated_path)
        white = new_tags[50717]
        assert white['type_id'] == 4 and white['count'] == 1
        assert AUDIT.numeric(white) == [record['white_level_value']]
        assert old_tags[50717]['type_id'] == 5
        assert AUDIT.numeric(old_tags[50717]) == AUDIT.numeric(white)
        assert new_strip == old_strip
        assert sha(new_strip) == record['encoded_strip_sha256']
        assert new_fields == old_fields
        before = (work/'native1a'/(name+'.input.bin')).read_bytes()
        after = (work/'native1a'/(name+'.after.bin')).read_bytes()
        if record['bits_per_sample'] == 16:
            assert before == after
            if record['compression'] == 1:
                assert before == new_strip
        cases.append({'case': name, 'result': 'pass', 'new_white_level_type': white['type'],
                      'white_level_count': white['count'], 'white_level': AUDIT.numeric(white)[0],
                      'old_dng_sha256': sha(old_file), 'new_dng_sha256': sha(new_file),
                      'encoded_strip_sha256': sha(new_strip), 'encoded_strip_unchanged': True,
                      'other_field_payloads_unchanged_except_strip_offset': True,
                      'uncompressed_raw16_matches_original_input': (new_strip == before) if record['bits_per_sample'] == 16 and record['compression'] == 1 else None})
    guards = json.loads((work/'native1a/guards.json').read_text())
    assert guards == {'invalid_native_calls_rejected': 12, 'representable_boundaries_accepted': 4}
    result = {
        'result': 'pass',
        'method': 'Read actual synthetic files generated by the old and changed production DngCreator.cpp through a separate bounded TIFF parser. Independently compared numeric tag type/count/value, encoded strip bytes and all unrelated field payloads. Reviewed the fixture source and confirmed its report hashes match current source files.',
        'production_source_review': {
            'both_native_branches_repaired': True,
            'finite_integral_unsigned32_guard_before_conversion': True,
            'guard_precedes_creator_allocations': True,
            'writer_failure_frees_optional_binned_buffer_and_returns_null': True,
            'retained_tiff_writer_source_modified': False,
            'software_uses_app_buildconfig': True,
            'software_compiled_apk_verification': 'pending final APK; tracked separately',
            'zero_white_level_scope': 'The helper tests representability, not exposure-metadata validity; zero remains representable as in the previous writer.'
        },
        'source_report': {'path': str(source_report), 'sha256': sha(source_report.read_bytes())},
        'retained_writer_provenance': {'native1_source_record': str(original_source_record),
                                      'source_record_sha256': sha(original_source_record.read_bytes()),
                                      'writer_path': writer_path,
                                      'writer_sha256_unchanged': original_writer['native1_sha256']},
        'verified_source_hashes': report['source_hashes'],
        'cases': cases,
        'guard_execution_record': guards,
        'guard_scope': 'The fixture invokes actual createDng for six invalid values at both 16- and 10-bit settings and checks null/size0/unchanged input. Boundary acceptance checks the production predicate; it does not claim a full physical-camera capture at uint32 limits.',
        'limits': ['No fixture was produced from or written over the user attachments.',
                   'No additional complete writer execution was required; the independently inspected fixture output came from the recorded actual host executions.',
                   'Host execution is not an Android camera test. No new independent JPEG-lossless decoder was used; compressed byte equality establishes preservation of the previous writer output.',
                   'The existing 10-bit packing branch mutates its buffer in both versions; the metadata fix leaves that behavior unchanged. The tested phone DNG used 16-bit storage.'],
    }
    destination = BASE/'hasselblad_device_validation_20261019/native1a_review/writer_fixture_independent_review.json'
    destination.write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({'result': 'pass', 'cases': len(cases), 'report': str(destination), 'sha256': sha(destination.read_bytes())}, indent=2))


if __name__ == '__main__':
    main()
